-- RNF03: catalog schema (book, author, category, copy), with
-- constraints that enforce RN01 (unique ISBN) and RN02 (unique asset code).

create table category (
    id     bigint generated by default as identity primary key,
    name   varchar(100) not null unique,
    active boolean      not null default true
);

create table author (
    id     bigint generated by default as identity primary key,
    name   varchar(150) not null,
    active boolean      not null default true
);

create table book (
    id                bigint generated by default as identity primary key,
    isbn              varchar(13)  not null unique,
    title             varchar(255) not null,
    publisher         varchar(255),
    publication_year  integer,
    category_id       bigint       not null references category (id),
    active            boolean      not null default true
);

create table book_author (
    book_id   bigint not null references book (id),
    author_id bigint not null references author (id),
    primary key (book_id, author_id)
);

create table copy (
    id          bigint generated by default as identity primary key,
    book_id     bigint      not null references book (id),
    asset_code  varchar(50) not null unique,
    status      varchar(20) not null
        check (status in ('AVAILABLE', 'BORROWED', 'RESERVED', 'DAMAGED', 'LOST')),
    active      boolean     not null default true,
    version     bigint      not null default 0
);

create index idx_book_title on book (title);
create index idx_book_category_id on book (category_id);
create index idx_book_author_author_id on book_author (author_id);
create index idx_copy_book_id on copy (book_id);
