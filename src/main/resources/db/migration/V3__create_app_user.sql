-- RF08, RF09, RNF07: the people who operate the system (administrator and
-- operator). The password only exists as a BCrypt hash; there is no column
-- for a plain-text password. Named "app_user" because both "user" and
-- "system_user" are reserved words in PostgreSQL. The login is unique and
-- mandatory; the role is restricted to the two profiles by a check constraint.

create table app_user (
    id             bigint generated by default as identity primary key,
    login          varchar(50)  not null unique,
    password_hash  varchar(100) not null,
    role           varchar(20)  not null
        check (role in ('ADMIN', 'OPERATOR')),
    active         boolean      not null default true
);
