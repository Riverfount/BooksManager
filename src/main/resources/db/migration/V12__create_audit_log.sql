-- RF27: the audit trail of the sensitive operations (who did what, to what, and when). It is append-only: the
-- application only inserts and reads, and a trigger refuses any UPDATE, so a line can never be rewritten. A line
-- is removed only by hand, to apply the retention policy documented in the deployment guide.
--
-- actor_id and actor_login are plain values, not a foreign key to app_user: the audit module does not depend on
-- the user module, and the trail must survive whatever happens to a user. Both are null for what nobody did (the
-- administrator created at startup, a login that names no known user). The login is kept beside the id so a line
-- reads on its own. Nothing here holds a password, a hash, a token or personal data of a reader: the target is
-- only a type and an id, and the summary is a short text that the use case writes.

create table audit_log (
    id           bigint generated by default as identity primary key,
    occurred_at  timestamptz  not null,
    actor_id     bigint,
    actor_login  varchar(50),
    action       varchar(40)  not null
        check (action in ('LOGIN_SUCCESS', 'LOGIN_FAILURE', 'LOGIN_LOCKOUT', 'USER_CREATED', 'USER_UPDATED',
                          'USER_DEACTIVATED', 'USER_UNBLOCKED', 'USER_PASSWORD_RESET', 'READER_BLOCKED',
                          'READER_UNBLOCKED', 'READER_DEACTIVATED', 'FINE_PAID', 'FINE_WAIVED',
                          'SUSPENSION_ENDED', 'LIBRARY_CONFIGURATION_UPDATED')),
    target_type  varchar(30)
        check (target_type in ('USER', 'READER', 'FINE', 'SUSPENSION', 'LIBRARY_CONFIGURATION')),
    target_id    bigint,
    summary      varchar(500),
    constraint audit_log_target_id_needs_type check (target_id is null or target_type is not null),
    constraint audit_log_login_needs_actor check (actor_login is null or actor_id is not null)
);

-- the default order of the listing (the newest first) and the filters of the listing
create index idx_audit_log_occurred_at on audit_log (occurred_at desc, id);
create index idx_audit_log_actor on audit_log (actor_id, occurred_at desc);
create index idx_audit_log_target on audit_log (target_type, target_id, occurred_at desc);

create function audit_log_refuse_update() returns trigger
    language plpgsql as $$
begin
    raise exception 'audit_log is append-only: a line cannot be changed';
end;
$$;

create trigger audit_log_no_update
    before update on audit_log
    for each row execute function audit_log_refuse_update();
