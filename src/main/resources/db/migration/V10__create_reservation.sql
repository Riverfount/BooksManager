-- RF16, RNF03, RNF17: reservation schema, with constraints that back the rules of the domain.
-- The partial unique indexes are the last line of defense against two active reservations of the
-- same book by the same reader (RN12) and against two reservations holding the same copy, even
-- when two requests race past the optimistic lock.
--
-- An active reservation is in one of two moments, derived and not stored: waiting in the queue
-- (no copy) or holding a copy until the pickup deadline (RN13). The queue of a book is its waiting
-- reservations in order of arrival, which is the order of the identity column.
-- The checks repeat the invariants of the domain class, which reports them to the user with
-- messages; the database only refuses what slips through.

create table reservation (
    id               bigint generated by default as identity primary key,
    book_id          bigint      not null references book (id),
    reader_id        bigint      not null references reader (id),
    copy_id          bigint references copy (id),
    pickup_deadline  date,
    status           varchar(10) not null
        check (status in ('ACTIVE', 'FULFILLED', 'CANCELLED', 'EXPIRED')),
    reservation_date date        not null,
    version          bigint      not null default 0,
    -- the copy kept for the reader and the last day to pick it up go together
    constraint reservation_copy_matches_deadline check ((copy_id is null) = (pickup_deadline is null)),
    -- a reservation that was picked up or expired had a copy; a cancelled one may never have had
    constraint reservation_closed_with_copy check (status in ('ACTIVE', 'CANCELLED') or copy_id is not null),
    constraint reservation_deadline_not_before_reservation check (
        pickup_deadline is null or pickup_deadline >= reservation_date)
);

-- RN12: at most one active reservation per reader and book
create unique index uq_reservation_active_reader_book on reservation (reader_id, book_id)
    where status = 'ACTIVE';
-- at most one active reservation holding a given copy
create unique index uq_reservation_active_copy on reservation (copy_id)
    where status = 'ACTIVE' and copy_id is not null;

-- the queue of a book: the waiting reservations, in order of arrival
create index idx_reservation_book_queue on reservation (book_id, id)
    where status = 'ACTIVE' and copy_id is null;
-- the expiry routine looks only at the active reservations that hold a copy
create index idx_reservation_active_deadline on reservation (pickup_deadline)
    where status = 'ACTIVE' and copy_id is not null;
-- the queries by reader (listing and count of active reservations)
create index idx_reservation_reader_id on reservation (reader_id);
