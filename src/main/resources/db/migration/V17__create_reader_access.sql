-- Phase 6 (RF08, RF17, RF27, RNF08): the reader gets a limited access to the system. The access is an app_user with the
-- READER profile tied to one reader (reader_id), and it is granted by an invitation the reader receives by e-mail.
--
-- A reader has at most one ACTIVE access (a revoked one stays, inactive, for the history, RN14; a new invitation
-- creates another). The READER profile and the reader go together: a READER has a reader, nobody else does. The V3
-- check on the role is replaced by a new one, and the V3 migration is not edited.
--
-- reader_access_token holds the invitation and the password reset link. The token is random and opaque, so only its
-- hash is stored (SHA-256 in hexadecimal, 64 characters), like the refresh token (V4); there is no column for the token.

alter table app_user
    drop constraint app_user_role_check,
    add constraint app_user_role_check check (role in ('ADMIN', 'OPERATOR', 'READER')),
    add column reader_id bigint references reader (id),
    add constraint app_user_reader_iff_reader_role check ((role = 'READER') = (reader_id is not null));

create unique index uq_app_user_active_reader on app_user (reader_id) where active and reader_id is not null;

create table reader_access_token (
    id          bigint generated by default as identity primary key,
    purpose     varchar(20) not null check (purpose in ('INVITATION', 'PASSWORD_RESET')),
    reader_id   bigint      not null references reader (id),
    token_hash  varchar(64) not null unique,
    created_at  timestamptz not null,
    expires_at  timestamptz not null,
    used_at     timestamptz,
    constraint reader_access_token_expires_after_created check (expires_at > created_at)
);

create index idx_reader_access_token_reader_id on reader_access_token (reader_id);

-- RF27: the audit trail records the access of the readers (invited, granted, revoked and password reset).
alter table audit_log
    drop constraint audit_log_action_check,
    add constraint audit_log_action_check
        check (action in ('LOGIN_SUCCESS', 'LOGIN_FAILURE', 'LOGIN_LOCKOUT', 'USER_CREATED', 'USER_UPDATED',
                          'USER_DEACTIVATED', 'USER_UNBLOCKED', 'USER_PASSWORD_RESET', 'READER_BLOCKED',
                          'READER_UNBLOCKED', 'READER_DEACTIVATED', 'FINE_PAID', 'FINE_WAIVED',
                          'SUSPENSION_ENDED', 'LIBRARY_CONFIGURATION_UPDATED',
                          'BOOK_DEACTIVATED', 'BOOK_REACTIVATED', 'AUTHOR_DEACTIVATED', 'AUTHOR_REACTIVATED',
                          'CATEGORY_DEACTIVATED', 'CATEGORY_REACTIVATED', 'COPY_DEACTIVATED',
                          'COPY_REACTIVATED', 'READER_ACCESS_INVITED', 'READER_ACCESS_GRANTED',
                          'READER_ACCESS_REVOKED', 'READER_PASSWORD_RESET'));
