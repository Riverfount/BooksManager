-- RF07, RF10, RNF11: reader table with only the minimal personal data (LGPD).
-- The document is unique and never null, so a unique marker (ANON-<id>) can
-- replace it in a future anonymization without losing the history (RN14); the
-- guardian data goes through the same anonymization. The guardian requirement
-- for readers under 18 is a domain rule, not a database constraint.

create table reader (
    id              bigint generated by default as identity primary key,
    name            varchar(150) not null,
    document        varchar(30)  not null unique,
    email           varchar(254) not null,
    phone           varchar(30),
    birth_date      date         not null,
    guardian_name   varchar(150),
    guardian_email  varchar(254),
    guardian_phone  varchar(30),
    active          boolean      not null default true,
    blocked         boolean      not null default false
);

create index idx_reader_name on reader (name);
