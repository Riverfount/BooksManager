-- RF08, RNF03, RNF07: refresh tokens. The token is opaque (random), so only
-- its hash is stored (SHA-256 in hexadecimal, 64 characters); there is no
-- column for the token itself. Rotation and revocation: using a token revokes
-- it (revoked_at) and points to the one that replaces it (replaced_by).
--
-- The foreign key to app_user has no cascade on purpose: a user with tokens
-- cannot be deleted, only deactivated (RN14). created_at has no default: the
-- application sets it from its Clock, like every other date.

create table refresh_token (
    id           bigint generated by default as identity primary key,
    user_id      bigint       not null references app_user (id),
    token_hash   varchar(64)  not null unique,
    expires_at   timestamptz  not null,
    revoked_at   timestamptz,
    replaced_by  bigint references refresh_token (id),
    created_at   timestamptz  not null,
    -- a token lives for some time after it is created
    constraint refresh_token_expires_after_created check (expires_at > created_at),
    -- a token that was replaced (rotated) is always revoked, and never by itself
    constraint refresh_token_replaced_is_revoked check (replaced_by is null or revoked_at is not null),
    constraint refresh_token_not_replaced_by_itself check (replaced_by is null or replaced_by <> id)
);

create index idx_refresh_token_user_id on refresh_token (user_id);
