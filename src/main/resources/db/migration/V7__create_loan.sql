-- RNF17, RNF03, RN03, RN05, RN15: loan schema (loan, fine, suspension), with
-- constraints that back the rules of the domain. The partial unique index is
-- the last line of defense against two active loans of the same copy, even
-- when two requests race past the optimistic lock (RNF17).
--
-- An active loan is one without a return date. There is no OVERDUE status:
-- a late loan is an active loan whose due date is in the past (RN05).
-- The checks repeat the invariants of the domain classes, which report them
-- to the user with messages; the database only refuses what slips through.
-- The suspension is a table of its own (decision of #135), pointing to the
-- reader and to the loan that caused it.

create table loan (
    id          bigint generated by default as identity primary key,
    copy_id     bigint  not null references copy (id),
    reader_id   bigint  not null references reader (id),
    pickup_date date    not null,
    due_date    date    not null,
    return_date date,
    renewals    integer not null default 0
        check (renewals >= 0),
    version     bigint  not null default 0,
    constraint loan_due_date_not_before_pickup check (due_date >= pickup_date),
    constraint loan_return_date_not_before_pickup check (return_date is null or return_date >= pickup_date)
);

-- RN03: at most one active loan per copy
create unique index uq_loan_active_copy on loan (copy_id) where return_date is null;

create index idx_loan_reader_id on loan (reader_id);
create index idx_loan_copy_id on loan (copy_id);
-- the overdue report looks only at active loans
create index idx_loan_active_due_date on loan (due_date) where return_date is null;

create table fine (
    id            bigint generated by default as identity primary key,
    loan_id       bigint         not null unique references loan (id),
    reader_id     bigint         not null references reader (id),
    amount        numeric(10, 2) not null
        check (amount > 0),
    status        varchar(10)    not null
        check (status in ('PENDING', 'PAID', 'WAIVED')),
    waiver_reason varchar(500),
    version       bigint         not null default 0,
    -- only a waived fine has a reason, and a waived fine always has one
    constraint fine_waiver_reason_matches_status check (
        (status = 'WAIVED' and waiver_reason is not null and btrim(waiver_reason) <> '')
        or (status <> 'WAIVED' and waiver_reason is null))
);

-- RN05: the pending fines of a reader block new loans
create index idx_fine_reader_pending on fine (reader_id) where status = 'PENDING';
create index idx_fine_reader_id on fine (reader_id);

create table suspension (
    id                 bigint generated by default as identity primary key,
    reader_id          bigint       not null references reader (id),
    loan_id            bigint       not null references loan (id),
    start_date         date         not null,
    end_date           date         not null,
    ended_early_on     date,
    ended_early_reason varchar(500),
    version            bigint       not null default 0,
    constraint suspension_end_after_start check (end_date > start_date),
    -- RN15: ending early always comes with a justification, and only then
    constraint suspension_early_end_has_reason check (
        (ended_early_on is null and ended_early_reason is null)
        or (ended_early_on is not null and ended_early_reason is not null and btrim(ended_early_reason) <> '')),
    constraint suspension_early_end_not_after_end check (ended_early_on is null or ended_early_on <= end_date)
);

create index idx_suspension_reader_id on suspension (reader_id);
create index idx_suspension_loan_id on suspension (loan_id);
