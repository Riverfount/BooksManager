-- RF28, RN16: the reader is told by e-mail that a loan is about to fall due and, once it is late, that it is
-- late. How many days before the due date the first notice goes out is a rule of the library, so it lives in the
-- configuration (default 2), never in the code.
alter table library_configuration
    add column due_soon_notice_days integer not null default 2
        check (due_soon_notice_days > 0);

-- What the routine already told, so that running it again on the same day sends nothing twice. One row is one
-- e-mail that went out: kind DUE_SOON is sent once per loan and due date (a renewal moves the due date, so it
-- is a new notice); kind OVERDUE is sent once per loan, due date and band of late days (band 0 is the 1st day
-- late, band 1 the 8th, band 2 the 15th, and so on, one band every 7 days). The unique key is what keeps two
-- concurrent runs from both recording the same notice.
create table loan_notice (
    id         bigint generated by default as identity primary key,
    loan_id    bigint      not null references loan (id),
    kind       varchar(20) not null
        check (kind in ('DUE_SOON', 'OVERDUE')),
    due_date   date        not null,
    band       integer     not null
        check (band >= 0),
    sent_on    date        not null,
    constraint loan_notice_once unique (loan_id, kind, due_date, band)
);
